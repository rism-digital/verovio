/**
 * Fix the generated verovio-toolkit.d.ts after tsc emit.
 *
 * The JSDoc typedefs in src/verovio-toolkit.js import from "./types/...", which
 * is correct relative to that file. However, tsc emits the declaration file to
 * src/types/verovio-toolkit.d.ts without rewriting the specifiers, so they need
 * to be adjusted to "./..." to resolve from the location of the emitted file.
 *
 * The typedef comments are also emitted from the JSDoc, where they are needed
 * to name the imported types. In the declaration file they duplicate the
 * export type aliases at the bottom of the file, so they are removed.
 *
 * Usage: node fix-verovio-toolkit.cjs
 */
const fs = require("node:fs");
const path = require("node:path");

const toolkitTypes = path.join(
    __dirname,
    "..",
    "..",
    "src",
    "types",
    "verovio-toolkit.d.ts",
);
const source = fs.readFileSync(toolkitTypes, "utf8");
const fixed =
    `
////////////////////////////////////////////////////////////////////////////////
// NOTE: this file was generated by the emscripten/npm build script
// and should not be edited because changes will be lost.
////////////////////////////////////////////////////////////////////////////////

`.trimStart() +
    source
        .replace(/import\("\.\/types\//g, 'import("./')
        .replace(/^\/\*\* @typedef \{.*\*\/\n/gm, "");
fs.writeFileSync(toolkitTypes, fixed);
